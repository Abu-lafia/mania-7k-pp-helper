const requested = new URL(location.href).searchParams.get('lang');
const preferred = requested === 'en' || requested === 'zh-CN' ? requested : saved;
export const language = preferred === 'en' || preferred === 'zh-CN' ? preferred : (navigator.language.startsWith('zh') ? 'zh-CN' : 'en');
export const locale = language === 'zh-CN' ? 'zh-CN' : 'en-GB';
export function t(text) {
  if (language !== 'zh-CN') return text;
  if (zh[text]) return zh[text];
  if (typeof text !== 'string') return text;
  let match = text.match(/^Enter an inclusive range between (.+) and (.+)\.$/);
  if (match) return `请输入 ${match[1]} 至 ${match[2]} 之间的范围（包含端点）。`;
  match = text.match(/^(.+) returned HTTP (\d+)\.$/);
  if (match) return `${match[1]} 返回 HTTP ${match[2]}。`;
  return text;
}
export function statusText(text) {
  return language === 'zh-CN' ? ({running:'运行中',complete:'已完成',cancelled:'已取消',error:'错误',saved:'已保存',queued:'排队中',downloading:'下载中',failed:'失败',partial:'部分完成',rankings:'排行榜',profiles:'玩家资料',tracker:'段位',best:'最佳成绩',calculation:'计算'}[text] ?? t(text)) : text;
}
export function initLanguage() {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script,style')) continue;
    const key = node.nodeValue.trim().replace(/\s+/g, ' ');
    if (zh[key]) node.nodeValue = node.nodeValue.replace(/\S[\s\S]*\S|\S/, t(key));
  }
  for (const node of document.querySelectorAll('[title],[aria-label],[placeholder]')) {
    for (const attr of ['title','aria-label','placeholder']) if (node.hasAttribute(attr)) node.setAttribute(attr,t(node.getAttribute(attr)));
  }
  const button = document.createElement('button');
  button.id = 'language-toggle'; button.className = 'secondary compact language-toggle';
  button.type = 'button';
  button.textContent = language === 'zh-CN' ? 'English' : '中文';
  button.title = button.textContent; button.setAttribute('aria-label', language === 'zh-CN' ? 'Switch to English' : '切换为简体中文');
  button.onclick = () => {
    const next = language === 'zh-CN' ? 'en' : 'zh-CN';
    try { localStorage.setItem('7khelper-language', next); } catch {}
    const url = new URL(location.href);
    url.searchParams.set('lang', next);
    location.assign(url.href);
  };
  document.querySelector('.header-actions').append(button);
}
